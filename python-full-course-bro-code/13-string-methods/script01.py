name  = input("Name: ")

length = len(name)
first = name.find(" ")
last = name.rfind("o")
c_name = name.capitalize()
u_name = name.upper()
l_name = name.lower()
digit = name.isdigit()
alphabet = name.isalpha()

print(length)
print(first)
print(last)
print(c_name)
print(u_name)
print(l_name)
print(digit)
print(alphabet)